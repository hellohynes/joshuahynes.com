// Refreshes src/data/contributions.ts from GitHub's contribution calendar for the account `gh` is signed in as.
// Run it with `pnpm contributions`. Only each day's intensity level (0-4) is stored, not counts, dates or
// repository names, so nothing private ends up in the repo.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const query = `query { viewer { contributionsCollection { contributionCalendar { weeks { contributionDays { weekday contributionLevel } } } } } }`
const out = execFileSync('gh', ['api', 'graphql', '-f', `query=${query}`], { encoding: 'utf8' })
const { weeks } = JSON.parse(out).data.viewer.contributionsCollection.contributionCalendar

const LEVEL = { NONE: '0', FIRST_QUARTILE: '1', SECOND_QUARTILE: '2', THIRD_QUARTILE: '3', FOURTH_QUARTILE: '4' }

// One 7-character string per week, Sunday first. A day that has not happened yet is "-".
const rows = weeks.map((week) => {
  const cells = Array.from({ length: 7 }, () => '-')
  for (const day of week.contributionDays) cells[day.weekday] = LEVEL[day.contributionLevel]
  return cells.join('')
})

const file = new URL('../src/data/contributions.ts', import.meta.url)
writeFileSync(
  file,
  `// Generated by scripts/update-contributions.mjs, do not edit by hand.
// One string per week, Sunday first. Each character is a day's contribution level, 0 (none) to 4 (most);
// "-" is a day that had not happened yet.
export const CONTRIBUTION_WEEKS: string[] = [
${rows.map((r) => `  '${r}',`).join('\n')}
]
`,
)
console.log(`wrote ${rows.length} weeks to src/data/contributions.ts`)
